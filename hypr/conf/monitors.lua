-- Список выходов и поддерживаемых режимов: hyprctl monitors all
-- Пока твои экраны неизвестны, используем предпочтительный режим монитора.
-- preferred не обязательно означает самую высокую доступную частоту.
hl.monitor({
    output = "",         -- Пустое имя: правило для выходов без отдельной настройки.
    mode = "preferred",  -- Разрешение и частота из EDID монитора.
    position = "auto",   -- Автоматически расположить экраны рядом.
    scale = "auto",      -- Масштаб выбирает Hyprland; для обычного 1080p можно "1".
})

