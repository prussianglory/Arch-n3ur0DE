-- Числовые ID сохраняем постоянными: к ним привяжутся Waybar и хоткеи.
-- Предлагаемое назначение (можно использовать иначе):
--   1 — терминал; 2 — код; 3 — браузер; 4 — заметки; 5 — файлы.
-- Приложения не переносим автоматически: открывай их на нужном столе.
for id = 1, 5 do
    hl.workspace_rule({
        workspace = tostring(id), -- Здесь API ожидает строковый селектор.
        persistent = true,        -- Не удалять стол, когда он опустел.
    })
end

-- Столы 6–10 создаются по мере обращения к ним.
-- Именованный скрываемый стол special:scratch:
-- Super+S показывает/скрывает; Super+Shift+S переносит туда текущее окно.
-- Внутри scratchpad сохраняем обычную раскладку dwindle.
hl.workspace_rule({ workspace = "special:scratch", gaps_out = 30, gaps_in = 5 })
